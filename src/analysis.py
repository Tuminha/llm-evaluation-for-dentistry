"""Reproduce manuscript summary tables from stored benchmark outputs.

This script is intentionally dependency-free. It reads the raw JSONL result files,
recomputes the primary leaderboard, bootstrap intervals, answer rates, mean
latencies, and secondary-judge agreement, then writes a compact markdown report.

Usage:
    python src/analysis.py
"""
from __future__ import annotations

import argparse
from collections import defaultdict
import json
from pathlib import Path
import random

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results"


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def pct(value: float) -> str:
    return f"{value:.1f}%"


def bootstrap_ci(values: list[bool], *, resamples: int = 10_000, seed: int = 42) -> tuple[float, float]:
    """Question-level nonparametric bootstrap CI used in the manuscript.

    The RNG is reset per model so the interval for a model is a pure function of
    that model's 30 binary outcomes. Percentile indexes are fixed to match the
    reported 10,000-resample procedure.
    """
    rng = random.Random(seed)
    n = len(values)
    draws: list[float] = []
    for _ in range(resamples):
        correct = sum(values[rng.randrange(n)] for _ in range(n))
        draws.append(100 * correct / n)
    draws.sort()
    lower_idx = int(0.025 * resamples)
    upper_idx = int(0.975 * resamples) - 1
    return draws[lower_idx], draws[upper_idx]


def cohen_kappa(primary: list[bool], secondary: list[bool]) -> float:
    n = len(primary)
    if n == 0:
        return float("nan")
    observed = sum(a == b for a, b in zip(primary, secondary)) / n
    primary_yes = sum(primary) / n
    secondary_yes = sum(secondary) / n
    expected = primary_yes * secondary_yes + (1 - primary_yes) * (1 - secondary_yes)
    return (observed - expected) / (1 - expected) if expected < 1 else 1.0


def primary_table(rows: list[dict]) -> list[dict]:
    by_model: dict[str, list[dict]] = defaultdict(list)
    for row in rows:
        by_model[row["model"]].append(row)

    table = []
    for model, model_rows in by_model.items():
        outcomes = [bool(row["correct"]) for row in model_rows]
        answered_rows = [row for row in model_rows if (row.get("answer") or "").strip()]
        ci_low, ci_high = bootstrap_ci(outcomes)
        accuracy = 100 * sum(outcomes) / len(outcomes)
        answer_rate = 100 * len(answered_rows) / len(model_rows)
        answered_accuracy = (
            100 * sum(bool(row["correct"]) for row in answered_rows) / len(answered_rows)
            if answered_rows else 0.0
        )
        latencies = [
            float(row["mean_latency_s"])
            for row in model_rows
            if row.get("mean_latency_s") is not None
        ]
        latency = sum(latencies) / len(latencies) if latencies else 0.0
        table.append({
            "model": model,
            "correct": sum(outcomes),
            "total": len(outcomes),
            "accuracy": accuracy,
            "ci_low": ci_low,
            "ci_high": ci_high,
            "answer_rate": answer_rate,
            "answered_accuracy": answered_accuracy,
            "latency": latency,
        })

    return sorted(table, key=lambda row: (row["accuracy"], row["answered_accuracy"]), reverse=True)


def judge_agreement(primary_rows: list[dict], secondary_rows: list[dict]) -> dict:
    primary_answered = [
        row for row in primary_rows
        if (row.get("answer") or "").strip()
    ]
    secondary_by_key = {
        (row["model"], row["qid"]): row
        for row in secondary_rows
        if not row.get("judge_error")
    }
    paired = [
        (row, secondary_by_key[(row["model"], row["qid"])])
        for row in primary_answered
        if (row["model"], row["qid"]) in secondary_by_key
    ]
    primary_verdicts = [bool(row1["correct"]) for row1, _ in paired]
    secondary_verdicts = [bool(row2["correct"]) for _, row2 in paired]
    agreement = sum(a == b for a, b in zip(primary_verdicts, secondary_verdicts)) / len(paired)
    return {
        "judge": paired[0][1]["judge"] if paired else "unknown",
        "paired": len(paired),
        "agreement": agreement,
        "kappa": cohen_kappa(primary_verdicts, secondary_verdicts),
    }


def write_report(rows: list[dict], judge_files: list[Path], out_path: Path) -> None:
    table = primary_table(rows)
    lines = [
        "# Reproducible Analysis Tables",
        "",
        "Generated by `python src/analysis.py` from the raw JSONL files.",
        "",
        "## Primary Benchmark Results",
        "",
        "| Model | Accuracy (95% CI) | Answer rate | Accuracy on answered | Mean latency |",
        "|---|---:|---:|---:|---:|",
    ]
    for row in table:
        lines.append(
            f"| {row['model']} | {pct(row['accuracy'])} "
            f"[{row['ci_low']:.1f}, {row['ci_high']:.1f}] | "
            f"{row['answer_rate']:.1f}% | {row['answered_accuracy']:.1f}% | "
            f"{row['latency']:.1f} s |"
        )

    lines.extend([
        "",
        "## Secondary Judge Agreement",
        "",
        "| Judge | Paired answered rows | Verdict agreement | Cohen's kappa |",
        "|---|---:|---:|---:|",
    ])
    for judge_file in judge_files:
        if not judge_file.exists():
            continue
        agreement = judge_agreement(rows, read_jsonl(judge_file))
        lines.append(
            f"| {agreement['judge']} | {agreement['paired']} | "
            f"{agreement['agreement']:.1%} | {agreement['kappa']:.3f} |"
        )

    out_path.write_text("\n".join(lines) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=RESULTS / "results.jsonl")
    parser.add_argument("--judge", action="append", type=Path)
    parser.add_argument("--out", type=Path, default=RESULTS / "analysis_tables.md")
    args = parser.parse_args()

    judge_files = args.judge or [
        RESULTS / "results_judge2.jsonl",
        RESULTS / "results_judge_gpt55.jsonl",
    ]
    rows = read_jsonl(args.results)
    write_report(rows, judge_files, args.out)
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
